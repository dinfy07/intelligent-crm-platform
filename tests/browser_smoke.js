 await page.getByRole('status').filter({hasText:'Analysis complete'}).waitFor();
 ok(await page.locator('.conversation img').count()===0,'Script-like imported text is never rendered as HTML');
 const downloadPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:'Export selected JSON',exact:true}).click();
 const download=await downloadPromise;
 await download.saveAs('docs/evidence/fixture_export.json');
 checks.push('Selected fictional result exported as JSON');
 await page.getByRole('button',{name:'Reject',exact:true}).click();
 ok(await page.getByText('Rejected by demo reviewer. Raw analysis is preserved.').isVisible(),'Rejection is explicit human review state');
 await page.setViewportSize({width:390,height:844});
